    fun searchHadiths(query: String): List<HadithItem> {
        val trimmed = query.trim()
        if (trimmed.isBlank()) return MUSNAD_HADITHS
        val normQuery = QuranCatalogData.normalizeArabic(trimmed)
        val numQuery = trimmed.toIntOrNull()
        return MUSNAD_HADITHS.filter { h ->
            (numQuery != null && h.hadithNumber == numQuery) ||
                QuranCatalogData.normalizeArabic(h.matn).contains(normQuery) ||
                QuranCatalogData.normalizeArabic(h.sanad).contains(normQuery) ||
                QuranCatalogData.normalizeArabic(h.narrator).contains(normQuery) ||
                QuranCatalogData.normalizeArabic(h.bookName).contains(normQuery) ||
                QuranCatalogData.normalizeArabic(h.chapterName).contains(normQuery) ||
                QuranCatalogData.normalizeArabic(h.explanation).contains(normQuery)
        }
    }
