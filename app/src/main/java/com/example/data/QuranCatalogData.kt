    /**
     * Normalizes Arabic text by removing tashkeel (diacritics), tatweel, and unifying Alef/Hamza variants
     * so users can search Quranic Uthmanic verses and Hadiths effortlessly with normal keyboard input.
     */
    fun normalizeArabic(input: String): String {
        val diacriticsRegex = Regex("[\\u0610-\\u061A\\u064B-\\u065F\\u0670\\u06D6-\\u06ED\\u0640]")
        return input
            .replace(diacriticsRegex, "")
            .replace('أ', 'ا')
            .replace('إ', 'ا')
            .replace('آ', 'ا')
            .replace('ٱ', 'ا')
            .replace('ة', 'ه')
            .replace('ى', 'ي')
            .trim()
    }
